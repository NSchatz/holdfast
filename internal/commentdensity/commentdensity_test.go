func TestCommentDensityKeepsTheExemptionListARatchet(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", densityFixture(4, 36))
	write(t, dir, "loud.go", densityFixture(35, 6))
	rep, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}

	good := []Exemption{{Path: "loud.go", Reason: "the invariant it records cannot be said shorter"}}
	if problems := ValidateExemptions(rep, good); len(problems) != 0 {
		t.Fatalf("a live exemption was rejected: %v", problems)
	}
	var out bytes.Buffer
	if err := Run(dir, &out, good); err != nil {
		t.Fatalf("an exempt file failed the run: %v", err)
	}
	if !strings.Contains(out.String(), "exempt: loud.go") {
		t.Errorf("the exempt file is not reported with its reason:\n%s", out.String())
	}

	tooMany := make([]Exemption, 0, MaxExemptions+1)
	for i := 0; i <= MaxExemptions; i++ {
		tooMany = append(tooMany, Exemption{Path: "loud.go", Reason: "why"})
	}
	if problems := ValidateExemptions(rep, tooMany); len(problems) == 0 ||
		!strings.Contains(problems[0], fmt.Sprintf("%d entries", MaxExemptions+1)) {
		t.Errorf("a list over the cap of %d was accepted: %v", MaxExemptions, problems)
	}

	gone := []Exemption{{Path: "deleted.go", Reason: "why"}}
	if problems := ValidateExemptions(rep, gone); len(problems) != 1 ||
		!strings.Contains(problems[0], "deleted.go") || !strings.Contains(problems[0], "does not exist") {
		t.Errorf("an exemption outliving its file was accepted: %v", problems)
	}

	under := []Exemption{{Path: "ok.go", Reason: "why"}}
	if problems := ValidateExemptions(rep, under); len(problems) != 1 ||
		!strings.Contains(problems[0], "ok.go") || !strings.Contains(problems[0], "ceiling") {
		t.Errorf("an exemption outliving the reason it was granted for was accepted: %v", problems)
	}
	if err := Run(dir, &bytes.Buffer{}, under); err == nil {
		t.Error("a stale exemption did not fail the run")
	}
}

func TestCommentDensityThresholdsStayInsideTheirBounds(t *testing.T) {
	if CeilingPct > 50 {
		t.Errorf("CeilingPct is %d, above the 50%% cap - a prose-heavy tree may not ratchet itself loose", CeilingPct)
	}
	if CeilingPct < 30 {
		t.Errorf("CeilingPct is %d, below the 30%% floor - the next legitimate doc comment would red the gate", CeilingPct)
	}
	if WarnPct != CeilingPct-10 {
		t.Errorf("WarnPct is %d and CeilingPct is %d: the warn band must be exactly 10 points below the ceiling",
			WarnPct, CeilingPct)
	}
}

func TestCommentDensityP90IsTheNearestRankAbove(t *testing.T) {
	var rep Report
	for i := 10; i >= 1; i-- {
		rep.Files = append(rep.Files, File{Path: fmt.Sprintf("f%d.go", i), Counts: Counts{Prose: i, Code: 100 - i}})
	}
	if got, want := rep.P90(), 0.09; got != want {
		t.Errorf("P90 = %v, want %v - rank ceil(0.90 * 10) = 9 of the ascending ratios", got, want)
	}
	if top, ok := rep.Max(); !ok || top.Path != "f10.go" {
		t.Errorf("Max = %v, want f10.go", top)
	}
}

