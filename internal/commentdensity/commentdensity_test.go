// The four comment shapes, with the counts written out. The trailing-comment line is
// the divergence that matters: Go's idiom would otherwise score ordinary code as prose.
const fourShapes = `// Package p is the package doc.
// It spans two lines.
package p

// Answer returns the answer.
func Answer() int {
	return 42 // the answer itself
}

/*
Block comment,
three lines of it.
*/
var x = 1

func blank() {

	_ = x
}
`

// Comment-looking bytes that are not comments: inside an interpreted string, inside a
// raw string, and a whole raw-string line that opens with the comment marker. A counter
// that matched patterns instead of tokens scores this file as prose, which is the exact
// failure that scored mostly-code files at 85% elsewhere.
const noComments = `package p

const site = "https://example.com//not-a-comment"

const doc = @
// looks like a comment
/* and so does this */
@

func use() string {
	return site + doc + "/* nor is this */"
}
`

func TestCommentDensityCountsTheFourCommentShapesExactly(t *testing.T) {
	m, err := Measure("four.go", []byte(fourShapes))
	if err != nil {
		t.Fatalf("Measure: %v", err)
	}
	if m.Prose != 7 || m.Code != 8 {
		t.Errorf("prose=%d code=%d, want prose=7 code=8 (package doc 2, doc comment 1, block 4; "+
			"the trailing-comment line is code)", m.Prose, m.Code)
	}
	if m.Generated {
		t.Error("a file with no generated marker was reported generated")
	}
}

func TestCommentDensityCountsNoProseInCommentLookingBytes(t *testing.T) {
	src := strings.ReplaceAll(noComments, "@", "`")
	m, err := Measure("strings.go", []byte(src))
	if err != nil {
		t.Fatalf("Measure: %v", err)
	}
	if m.Prose != 0 {
		t.Errorf("prose=%d, want 0 - no line of this file is spanned by a comment", m.Prose)
	}
	if m.Code != 9 {
		t.Errorf("code=%d, want 9 - every non-blank line here is code, including the raw string's", m.Code)
	}
}

func TestCommentDensityExcludesTestdataGeneratedAndSmallFiles(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", densityFixture(4, 36))
	write(t, dir, filepath.Join("testdata", "loud.go"), densityFixture(35, 6))
	write(t, dir, "generated.go", "// Code generated by hand. DO NOT EDIT.\n"+densityFixture(35, 6))
	write(t, dir, "small.go", densityFixture(20, 5))

	var out bytes.Buffer
	if err := Run(dir, &out, nil); err != nil {
		t.Fatalf("an excluded file was allowed to fail the run: %v\n%s", err, out.String())
	}
	got := out.String()
	if !strings.Contains(got, "1 eligible file(s)") {
		t.Errorf("want exactly one eligible file in the summary:\n%s", got)
	}
	for _, name := range []string{"loud.go", "generated.go", "small.go"} {
		if strings.Contains(got, name) {
			t.Errorf("%s was named by a run that must not measure it:\n%s", name, got)
		}
	}
	if !strings.Contains(got, "ok.go") {
		t.Errorf("the one eligible file was not measured:\n%s", got)
	}
}

func TestCommentDensityFailsAndNamesAFileOverTheCeiling(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", densityFixture(4, 36))
	write(t, dir, "loud.go", densityFixture(35, 6))

	var out bytes.Buffer
	err := Run(dir, &out, nil)
	if err == nil {
		t.Fatalf("a file over the %d%% ceiling did not fail the run:\n%s", CeilingPct, out.String())
	}
	if !strings.Contains(err.Error(), "loud.go") {
		t.Errorf("the failure does not name the file: %v", err)
	}
	if !strings.Contains(err.Error(), fmt.Sprintf("%d%% ceiling", CeilingPct)) {
		t.Errorf("the failure does not name the ceiling it broke: %v", err)
	}
	if !strings.Contains(out.String(), "85.4%") {
		t.Errorf("the failure does not report the ratio:\n%s", out.String())
	}
}

func TestCommentDensityWarnsInTheBandAndStaysGreen(t *testing.T) {
	dir := t.TempDir()
	prose := (WarnPct + CeilingPct) * 40 / 200
	body := densityFixture(prose, 40-prose)
	m, err := Measure("banded.go", []byte(body))
	if err != nil {
		t.Fatalf("Measure: %v", err)
	}
	if !m.InBand() {
		t.Fatalf("the fixture is not inside the band: prose=%d code=%d", m.Prose, m.Code)
	}
	write(t, dir, "banded.go", body)
	write(t, dir, "ok.go", densityFixture(4, 36))

	var out bytes.Buffer
	if err := Run(dir, &out, nil); err != nil {
		t.Fatalf("a banded file made the run non-zero: %v", err)
	}
	want := fmt.Sprintf("warn: banded.go at %.1f%%", m.Ratio()*100)
	if !strings.Contains(out.String(), want) {
		t.Errorf("no warning naming the file and its ratio (%q):\n%s", want, out.String())
	}
}

func TestCommentDensityFailsOnAnUnparseableFile(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", densityFixture(4, 36))
	write(t, dir, "broken.go", "package p\n\nfunc (\n")

	var out bytes.Buffer
	err := Run(dir, &out, nil)
	if err == nil {
		t.Fatal("an unparseable file was scored rather than reported")
	}
	if !strings.Contains(err.Error(), "broken.go") || !strings.Contains(err.Error(), "cannot be parsed") {
		t.Errorf("the failure does not name the file and the parser's error: %v", err)
	}
	if !strings.Contains(out.String(), "1 eligible file(s)") {
		t.Errorf("the unparseable file was counted in the aggregate:\n%s", out.String())
	}
}

func TestCommentDensityFailsOnAnUnreadableFile(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "ok.go", densityFixture(4, 36))
	secret := filepath.Join(dir, "secret.go")
	write(t, dir, "secret.go", densityFixture(4, 36))
	if err := os.Chmod(secret, 0o000); err != nil {
		t.Fatalf("chmod: %v", err)
	}
	t.Cleanup(func() { _ = os.Chmod(secret, 0o644) })
	if _, err := os.ReadFile(secret); err == nil {
		t.Skip("this user reads a mode-000 file, so the unreadable case cannot be planted here")
	}

	var out bytes.Buffer
	err := Run(dir, &out, nil)
	if err == nil {
		t.Fatal("an unreadable file was treated as absent")
	}
	if !strings.Contains(err.Error(), "secret.go") || !strings.Contains(err.Error(), "cannot be read") {
		t.Errorf("the failure does not name the path and the underlying error: %v", err)
	}
}

