// --- auth --------------------------------------------------------------------

// requireToken gates mutating endpoints. With no token resolved, control is
// DISABLED (403) - remote control is off until an operator opts in by pointing
// server_auth_token at a secret. A resolved token is compared in constant time, and it
// is never written to a response body, a header or a log: the 401 says "unauthorized"
// and nothing about what would have been accepted.
func (s *Server) requireToken(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if s.token.Empty() {
			http.Error(w, "control disabled: point server_auth_token at a secret "+
				"(file:/run/secrets/... or cmd:...) to enable rescan/pause/resume, the ledger search "+
				"and the withheld paths - see docs/secrets.md",
				http.StatusForbidden)
			return
		}
		got := bearerToken(r.Header.Get("Authorization"))
		if subtle.ConstantTimeCompare([]byte(got), []byte(s.token.Expose())) != 1 {
			w.Header().Set("WWW-Authenticate", `Bearer realm="holdfast"`)
			http.Error(w, "unauthorized", http.StatusUnauthorized)
			return
		}
		next.ServeHTTP(w, r)
	})
}

// requireReadToken gates the read endpoints under /api on `server_read_token`. With no
// read token resolved it is a pass-through: the read surface is OPEN, which is the
// shipped default and every existing install's behaviour, and a key that gated on upgrade
// would lock out every client that never sent a credential.
//
// With one resolved, a request must present EITHER the read token OR the control token.
// The control token is accepted here because one Authorization header cannot carry two
// values, so an operator holding the more privileged credential would otherwise be locked
// out of the less privileged surface. The reverse never holds: requireToken compares
// against the control token alone, so a read token buys no mutation.
//
// Both comparisons are constant time and BOTH ARE ALWAYS RUN - the results are combined
// with a bitwise OR rather than `||`, because a short circuit would make the response
// time say which of the two credentials was presented. Neither value reaches a response
// body, a header or a log: the 401 says "unauthorized" and nothing about what would have
// been accepted, and it names no media path, which is the whole reason this gate exists.
//
// It is MIDDLEWARE, so /api/events is refused before handleEvents runs at all: no
// snapshot, no heartbeat and no path is written to an unauthenticated stream.
func (s *Server) requireReadToken(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if s.readToken.Empty() {
			next.ServeHTTP(w, r)
			return
		}
		presented := []byte(bearerToken(r.Header.Get("Authorization")))
		ok := subtle.ConstantTimeCompare(presented, []byte(s.readToken.Expose()))
		// The control token is only a credential when one is configured. Without this
		// guard an EMPTY control token would compare equal to an absent Authorization
		// header, and a daemon with the controls disabled would serve its read API to
		// anyone who sent no credential at all - the exact hole this gate closes.
		if !s.token.Empty() {
			ok |= subtle.ConstantTimeCompare(presented, []byte(s.token.Expose()))
		}
		if ok != 1 {
			w.Header().Set("WWW-Authenticate", `Bearer realm="holdfast"`)
			http.Error(w, "unauthorized", http.StatusUnauthorized)
			return
		}
		next.ServeHTTP(w, r)
	})
}

// NodePathPrefix is the path the worker-node lease endpoints sit under. The version is in
// the path: a worker and a server run the same holdfast version, and a later protocol
// would be mounted beside this one.
const NodePathPrefix = "/api/node/v1"

// SetNodeToken hands the server the RESOLVED node credential (`node_token`). Set it once,
// before serving. The lease routes exist either way, so the surface is the same in every
// deployment, and they answer 403 until a non-empty value is set.
func (s *Server) SetNodeToken(token secret.Value) { s.nodeToken = token }

// SetNodes wires the lease protocol's server side. Set it once, before serving. Until it
// is set the lease endpoints answer 503 behind their credential.
func (s *Server) SetNodes(h *node.Hub) { s.nodes = h }

// requireNodeToken gates the lease endpoints on `node_token`, and on nothing else. With no
// node credential resolved the endpoints are DISABLED (403), as every mutating endpoint is
// without its credential: nodes are off until an operator opts in.
//
// The control token, the read token and the webhook token are NOT accepted here, and this
// credential authorises nothing anywhere else - the other gates compare against their own
// tokens only - so a stolen node token can lease a job and upload a candidate and cannot
// pause, exclude, search, scan or queue. The comparison is constant time, and the
// credential never reaches a response body, a header or a log.
func (s *Server) requireNodeToken(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if s.nodeToken.Empty() {
			http.Error(w, "worker nodes disabled: point node_token at a secret "+
				"(file:/run/secrets/... or cmd:...) to enable the lease endpoints under "+
				NodePathPrefix+" - see docs/secrets.md",
				http.StatusForbidden)
			return
		}
		got := bearerToken(r.Header.Get("Authorization"))
		if subtle.ConstantTimeCompare([]byte(got), []byte(s.nodeToken.Expose())) != 1 {
			w.Header().Set("WWW-Authenticate", `Bearer realm="holdfast"`)
			http.Error(w, "unauthorized", http.StatusUnauthorized)
			return
		}
		next.ServeHTTP(w, r)
	})
}

// bearerToken extracts the token from an "Authorization: Bearer <token>" header
// (case-insensitive scheme), or "" if absent/malformed.
func bearerToken(header string) string {
	const prefix = "bearer "
	if len(header) < len(prefix) || !strings.EqualFold(header[:len(prefix)], prefix) {
		return ""
	}
	return strings.TrimSpace(header[len(prefix):])
}

// --- helpers -----------------------------------------------------------------

func writeJSON(w http.ResponseWriter, code int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(code)
	_ = json.NewEncoder(w).Encode(v)
}

// writeSSE writes one SSE "snapshot" event. data is compact JSON (no embedded
// newlines), so a single data: line is correct.
func writeSSE(w http.ResponseWriter, data []byte) {
	_, _ = fmt.Fprintf(w, "event: snapshot\ndata: %s\n\n", data)
}

// handleHealth answers GET /api/health from the reporting door: the sweep under way, the
// last one that finished, and the files each found corrupt or unreadable.
func (s *Server) handleHealth(w http.ResponseWriter, r *http.Request) {
	live := health.Live{State: health.StateOff}
	if s.health != nil {
		live = s.health.Live()
	}
	rep, err := health.BuildReport(r.Context(), s.reads(), s.cfg.HealthSweepInterval(), live)
	if err != nil {
		s.fail(w, "health", err)
		return
	}
	writeJSON(w, http.StatusOK, rep)
}

func (s *Server) fail(w http.ResponseWriter, what string, err error) {
	s.log.Warn("api read failed", "endpoint", what, "err", err)
	http.Error(w, "internal error reading "+what, http.StatusInternalServerError)
}

// StartScanLoop kicks an initial scan (unless paused) and, when intervalSec > 0,
// re-scans on that interval until ctx is cancelled. It is the serve command's
// driver; overlap and pause are handled by the Controller (a tick that lands while
// a scan runs or while paused is simply refused). Runs in the caller's goroutine —
// serve launches it in the background.
func (s *Server) StartScanLoop(ctx context.Context, intervalSec int) {
	if started, reason := s.ctrl.Rescan(); !started {
		s.log.Info("initial scan not started", "reason", reason)
	}
	if intervalSec <= 0 {
		return
	}
	ticker := time.NewTicker(time.Duration(intervalSec) * time.Second)
	defer ticker.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			if started, reason := s.ctrl.Rescan(); !started {
				s.log.Debug("periodic scan skipped", "reason", reason)
			}
		}
	}
}
