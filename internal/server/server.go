// controlState is the at-a-glance status payload (no per-job rows). It carries BOTH
// the durable lifetime reclaimed total (TRANSCODE-14 — the figure that survives a
// restart) and the per-process session figure, mirroring the SSE snapshot so a client
// polling /api/summary sees the same two numbers the live stream pushes.
//
// It also carries the whole-ledger aggregates (DASH-7) under the same key and the same
// shape the SSE snapshot uses, so the figures are not reachable only over a live stream:
// a client that polls sees exactly what a client that subscribes sees. Like every other
// field here they are aggregates, so this adds no per-file datum to a read surface that
// needs no authorization.
type controlState struct {
	Summary                map[string]int `json:"summary"`
	BytesReclaimedSession  int64          `json:"bytes_reclaimed_session"`
	BytesReclaimedLifetime int64          `json:"bytes_reclaimed_lifetime"`
	Paused                 bool           `json:"paused"`
	Scanning               bool           `json:"scanning"`
	Aggregates             aggregatesDTO  `json:"aggregates"`
}

func (s *Server) handleSummary(w http.ResponseWriter, r *http.Request) {
	sum, err := s.reads().Summary(r.Context())
	if err != nil {
		s.fail(w, "summary", err)
		return
	}
	counts := make(map[string]int, len(sum))
	for st, n := range sum {
		counts[string(st)] = n
	}
	// The same whole-ledger figure set the stream publishes, from the same cache and
	// under the same refresh interval: a client that polls sees what a client that
	// subscribes sees, and polling this endpoint cannot make the figures cost more than
	// one refresh per interval however often it is called.
	writeJSON(w, http.StatusOK, controlState{
		Summary:                counts,
		BytesReclaimedSession:  s.hub.BytesReclaimed(),
		BytesReclaimedLifetime: s.hub.ReclaimedLifetime(),
		Paused:                 s.ctrl.Paused(),
		Scanning:               s.ctrl.Scanning(),
		Aggregates:             aggregatesOf(s.hub.ledgerFigures(r.Context(), true)),
	})
}

// The named wire shapes for the handlers that used to encode an anonymous map literal
// (S0128). They exist so the surface document has a CLOSED set of named fields to
// describe for every JSON endpoint: a map[string]any is an open object, and a document
// declaring one makes every validator pass while describing nothing at all.
//
// THE FIELD ORDER IS THE MAP'S OWN, which is alphabetical, because encoding/json sorts a
// map's keys and writes a struct's fields in declaration order. These types therefore
// encode BYTE-IDENTICAL JSON to the literals they replaced - asserted in schema_test.go -
// so no caller sees a change and the diff gate sees no difference from this task.

// queueResponse is the body of GET /api/queue.
type queueResponse struct {
	Now        int64       `json:"now"`
	Queue      []jobDTO    `json:"queue"`
	QueueTotal rowTotalDTO `json:"queue_total"`
}

// historyResponse is the body of GET /api/history.
type historyResponse struct {
	History      []jobDTO    `json:"history"`
	HistoryTotal rowTotalDTO `json:"history_total"`
}

// rescanResponse is the body of POST /api/rescan, under 202 and under 409 alike.
type rescanResponse struct {
	Paused   bool   `json:"paused"`
	Reason   string `json:"reason"`
	Scanning bool   `json:"scanning"`
	Started  bool   `json:"started"`
}

// controlToggleResponse is the body of POST /api/pause and POST /api/resume.
type controlToggleResponse struct {
	Paused   bool `json:"paused"`
	Scanning bool `json:"scanning"`
}

func (s *Server) handleQueue(w http.ResponseWriter, r *http.Request) {
	jobs, err := s.reads().List(r.Context(), activeAndPending, queueLimit)
	if err != nil {
		s.fail(w, "queue", err)
		return
	}
	// Same projection the SSE snapshot uses, live progress included, and the same "now"
	// basis for an in-state age — a client that polls this endpoint must not see a
	// different picture of a running job than one watching the stream.
	//
	// queue_total is the same field, under the same name and in the same shape, that the
	// SSE snapshot carries: the count of matching rows in the ledger, so a response that
	// shipped at most queueLimit of them says what it capped against instead of leaving a
	// client to derive it.
	writeJSON(w, http.StatusOK, queueResponse{
		Now:        time.Now().Unix(),
		Queue:      s.hub.queueDTOs(jobs),
		QueueTotal: rowTotalOf(s.hub.ledgerFigures(r.Context(), true).QueueTotal, queueLimit),
	})
}

func (s *Server) handleHistory(w http.ResponseWriter, r *http.Request) {
	limit := historyLimit
	if q := r.URL.Query().Get("limit"); q != "" {
		// Clamp a requested limit into (0, historyLimit]; anything larger keeps the
		// cap, anything else keeps the default. `<=` lets a caller ask for exactly
		// the cap.
		if n, err := strconv.Atoi(q); err == nil && n > 0 && n <= limit {
			limit = n
		}
	}
	jobs, err := s.reads().List(r.Context(), terminal, limit)
	if err != nil {
		s.fail(w, "history", err)
		return
	}
	// history_total counts the matching rows in the LEDGER, so it is the same figure
	// whether the caller took the cap or asked for fewer: `cap` moves with the request,
	// `count` does not. A total that tracked the request would just be len(history).
	writeJSON(w, http.StatusOK, historyResponse{
		History:      toDTOs(jobs),
		HistoryTotal: rowTotalOf(s.hub.ledgerFigures(r.Context(), true).HistoryTotal, limit),
	})
}

// handleEvents is the SSE stream: an initial snapshot, then a fresh snapshot on
// every engine transition / control change, plus a periodic heartbeat comment so
// idle connections (and proxies) stay open.
func (s *Server) handleEvents(w http.ResponseWriter, r *http.Request) {
	flusher, ok := w.(http.Flusher)
	if !ok {
		http.Error(w, "streaming unsupported", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")
	w.Header().Set("X-Accel-Buffering", "no") // disable proxy buffering (nginx)

	// Subscribe builds this client's own first frame and seeds the channel with it, so
	// the initial state a just-connected client renders is read AT THE MOMENT IT
	// SUBSCRIBED. The handler no longer takes a second snapshot of its own: one build
	// per subscription, arriving on the same channel as every frame after it.
	ch, cancel := s.hub.Subscribe(r.Context())
	defer cancel()

	heartbeat := time.NewTicker(25 * time.Second)
	defer heartbeat.Stop()

	for {
		select {
		case <-r.Context().Done():
			return
		case <-s.baseCtx.Done(): // server shutting down — release the stream
			return
		case data := <-ch:
			writeSSE(w, data)
			flusher.Flush()
		case <-heartbeat.C:
			_, _ = fmt.Fprint(w, ": ping\n\n")
			flusher.Flush()
		}
	}
}

// --- mutating endpoints (token-gated) ----------------------------------------

func (s *Server) handleRescan(w http.ResponseWriter, _ *http.Request) {
	started, reason := s.ctrl.Rescan()
	code := http.StatusAccepted
	if !started {
		code = http.StatusConflict // paused / already scanning
	}
	writeJSON(w, code, rescanResponse{
		Paused:   s.ctrl.Paused(),
		Reason:   reason,
		Scanning: s.ctrl.Scanning(),
		Started:  started,
	})
}

