// TRANSCODE-15 (1): the render idiom. Rows are built as DOM nodes (createElement +
// textContent), NEVER by assigning an HTML string to a sink — the untrusted data here is
// attacker-influencable media file paths. The page must therefore contain no HTML-sink
// assignment at all: no innerHTML / outerHTML / insertAdjacentHTML / document.write.
//
// WEBUI-10 extends it across EVERY source module. The page is now generated by
// concatenating them, so a sink in any one of them is a sink in the served document, and
// checking only the generated file would leave the source it came from unchecked.
func TestRenderIdiom_NoHTMLStringSinkFromJobData(t *testing.T) {
	files := map[string]string{"internal/webui/index.html": string(indexHTML)}
	for _, p := range dashboardSources(t) {
		files[p] = readFile(t, p)
	}
	if len(files) < 5 {
		t.Fatalf("the render-idiom sweep is looking at only %d files; it must cover every module", len(files))
	}
	for name, body := range files {
		if probs := htmlSinkProblems(body); probs != nil {
			t.Errorf("%s uses an HTML-string sink (%s) — rows must be built with createElement + "+
				"textContent, so an attacker-influencable path is inert text", name, strings.Join(probs, ", "))
		}
	}
	// The check must BITE: the same sweep over a module that DOES assign job data to a
	// sink has to report it, for every sink the criterion names.
	for _, bad := range []string{
		`el.innerHTML = j.path;`,
		`el.outerHTML = "<td>" + j.path + "</td>";`,
		`el.insertAdjacentHTML("beforeend", j.reason);`,
		`document.write(a.covers);`,
		`el.srcdoc = j.path;`,
		`document.createRange().createContextualFragment(j.path);`,
		`new DOMParser().parseFromString(j.path, "text/html");`,
		`el.setHTMLUnsafe(j.path);`,
		`eval("render(" + j.path + ")");`,
		`new Function("return " + j.path)();`,
	} {
		if htmlSinkProblems(bad) == nil {
			t.Errorf("the render-idiom sweep passed %q, so it cannot fail", bad)
		}
	}
	// And the prescribed structure primitives are actually used.
	s := string(indexHTML)
	for _, want := range []string{"createElement", "textContent", "<template", ".content.cloneNode"} {
		if !strings.Contains(s, want) {
			t.Errorf("index.html missing the safe-render primitive %q", want)
		}
	}
}

// htmlSinkProblems names every way a body reaches the DOM through a string rather than
// through a node. `document.write` and the parse-a-string constructors are equivalents of
// innerHTML for this purpose: each turns text into markup.
func htmlSinkProblems(body string) []string {
	var out []string
	for _, sink := range []string{
		"innerHTML", "outerHTML", "insertAdjacentHTML", "document.write",
		"srcdoc", "createContextualFragment", "DOMParser", "setHTMLUnsafe",
		"eval(", "new Function(",
	} {
		if strings.Contains(body, sink) {
			out = append(out, sink)
		}
	}
	return out
}

// dashboardSources is every file the generated document is built from, plus the unit
// suite that exercises them.
func dashboardSources(t *testing.T) []string {
	t.Helper()
	var out []string
	err := filepath.WalkDir(srcDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			out = append(out, p)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walking %s: %v", srcDir, err)
	}
	return out
}

// B16. The response Content-Security-Policy still contains `default-src 'none'` and
// `require-trusted-types-for 'script'`, and adds NO source expression admitting a resource
// or an evaluation the current policy refuses.
//
// The byte-for-byte assertion below (TestCSP_ByteForByteUnchangedAndStillEnforcesTrustedTypes)
// catches any change at all. This one says WHICH changes are the dangerous ones, and is
// proved against a table of policies that each widen it by exactly one thing - so it is a
// rule about policies, not a second copy of the string.
func TestCSP_AdmitsNothingTheCurrentPolicyRefuses(t *testing.T) {
	rec := httptest.NewRecorder()
	Handler().ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/", nil))
	got := rec.Header().Get("Content-Security-Policy")
	if probs := cspProblems(got); probs != nil {
		t.Errorf("the served policy %q admits something it must not: %v", got, probs)
	}

	// The rule must BITE. Each of these is a real way this policy gets widened.
	for _, widened := range []string{
		"default-src 'self'; require-trusted-types-for 'script'",
		"default-src 'none'; script-src 'unsafe-inline' 'unsafe-eval'; require-trusted-types-for 'script'",
		"default-src 'none'; img-src 'self'; require-trusted-types-for 'script'",
		"default-src 'none'; img-src data:; require-trusted-types-for 'script'",
		"default-src 'none'; script-src 'unsafe-inline' https://cdn.example.com; require-trusted-types-for 'script'",
		"default-src 'none'; script-src 'nonce-abc123'; require-trusted-types-for 'script'",
		"default-src 'none'; script-src 'sha256-abc'; require-trusted-types-for 'script'",
		"default-src 'none'; script-src 'strict-dynamic'; require-trusted-types-for 'script'",
		"default-src 'none'; connect-src *; require-trusted-types-for 'script'",
		"default-src 'none'; require-trusted-types-for 'script'; trusted-types default",
		"default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'self'",
		"style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'self'; require-trusted-types-for 'script'",
	} {
		if cspProblems(widened) == nil {
			t.Errorf("the policy rule accepted a widened policy, so it cannot fail: %q", widened)
		}
	}
}

// cspProblems reports every way a policy is weaker than the one this page is served with.
//
// The allow-list is a CLOSED set on purpose. A directive nobody thought about, or a source
// expression that names a host, a scheme, a nonce or a hash, is exactly the change that
// passes a "still contains default-src 'none'" test and quietly opens the page up.
func cspProblems(policy string) []string {
	allowedDirectives := map[string][]string{
		"default-src":               {"'none'"},
		"style-src":                 {"'unsafe-inline'"},
		"script-src":                {"'unsafe-inline'"},
		"connect-src":               {"'self'"},
		"require-trusted-types-for": {"'script'"},
	}
	var out []string
	seen := map[string]bool{}
	for _, raw := range strings.Split(policy, ";") {
		fields := strings.Fields(raw)
		if len(fields) == 0 {
			continue
		}
		name := strings.ToLower(fields[0])
		seen[name] = true
		allowed, ok := allowedDirectives[name]
		if !ok {
			out = append(out, "the directive "+name+" is not in the policy this page is served with")
			continue
		}
		for _, src := range fields[1:] {
			if !slices.Contains(allowed, strings.ToLower(src)) {
				out = append(out, "the directive "+name+" carries the source expression "+src+
					", which admits something the current policy refuses")
			}
		}
	}
	for name := range allowedDirectives {
		if !seen[name] {
			out = append(out, "the directive "+name+" is missing")
		}
	}
	return out
}

